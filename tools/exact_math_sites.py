#!/usr/bin/env python3
"""Writes src/exact_math_sites.inc: the places in LBP3's code (CUSA00473 1.28) that use rcpps, rsqrtps and dpps.

Their results can differ between CPU makers, which desynchronizes online play; exact_math_install (src/probe.c)
sends each site to a stub. A site needs a 5-byte jump, so a 4-byte one moves the next instruction to its stub.

Usage: exact_math_sites.py <out.inc> <image offset>:<code segment, loaded at 0>:<llvm-objdump -d --no-show-raw-insn output> ...
The eboot's image offset is 0; a module's is on the log's "Linked modules" line.
"""
import re
import struct
import sys

SITES = ('vrcpps', 'vrsqrtps', 'vdpps')
line = re.compile(r'^\s*([0-9a-f]+):\s+(\S+)\s*(.*)$')
rows = []


def scan(base, code_path, listing_path):
    code = open(code_path, 'rb').read()
    instructions = []
    for text in open(listing_path, encoding='ascii', errors='ignore'):
        match = line.match(text)
        if match:
            instructions.append((int(match[1], 16), match[2], match[3]))

    targets = set()
    for address, mnemonic, operands in instructions:
        if mnemonic.startswith(('j', 'loop')) or mnemonic == 'call':
            found = re.search(r'<\.text\+0x([0-9a-f]+)>', operands) or re.match(r'0x([0-9a-f]+)', operands)
            if found:
                targets.add(int(found[1], 16))

    def rip_field(start, end, operands):
        """Where the 32-bit RIP displacement of the instruction at start..end sits."""
        target = re.search(r'# 0x([0-9a-f]+)', operands)
        if '(%rip)' not in operands or not target:
            return None
        wanted = struct.pack('<i', int(target[1], 16) - end)
        at = code.find(wanted, start, end)
        if at < 0:
            raise SystemExit(f'no displacement found at {start:#x}')
        return at

    found, skipped = 0, 0
    for index, (address, mnemonic, operands) in enumerate(instructions):
        if mnemonic not in SITES:
            continue
        if code[address] not in (0xc4, 0xc5):
            skipped += 1
            continue
        site_end = instructions[index + 1][0]
        total_end, moved = site_end, None
        if site_end - address < 5:
            moved = instructions[index + 1]
            total_end = instructions[index + 2][0]
        rip = rip_field(address, site_end, operands)
        rip_next = site_end
        unusable = any(x in targets for x in range(address + 1, total_end))
        if moved:
            if moved[1].startswith(('j', 'loop', 'ret')) or moved[1] == 'call' or moved[1] in SITES or '%fs:' in moved[2]:
                unusable = True
            moved_rip = rip_field(moved[0], total_end, moved[2])
            if moved_rip is not None:
                rip, rip_next = moved_rip, total_end
        if unusable:
            skipped += 1
            print(f'skipped {base + address:#x}: {mnemonic} {operands}')
            continue
        rows.append((base + address, site_end - address, total_end - address,
                     rip - address if rip is not None else 0, rip_next - address))
        found += 1
    print(f'{code_path}: {found} sites, {skipped} skipped')


for spec in sys.argv[2:]:
    base, code_path, listing_path = spec.split(':', 2)
    scan(int(base, 0), code_path, listing_path)

with open(sys.argv[1], 'w', newline='\n') as out:
    out.write('/* Generated by tools/exact_math_sites.py: offset, site length, bytes moved, RIP field, its instruction end. */\n')
    for row in rows:
        out.write('{%#x,%d,%d,%d,%d},\n' % row)
print(f'{len(rows)} sites')
